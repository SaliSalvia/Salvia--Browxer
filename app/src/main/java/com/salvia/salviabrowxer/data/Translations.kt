    fun resolveLocale(mode: LanguageMode): String = when (mode) {
        LanguageMode.EN -> "en"
        LanguageMode.FA -> "fa"
        LanguageMode.SYSTEM -> if (Locale.getDefault().language.equals("fa", ignoreCase = true)) "fa" else "en"
    }

    fun t(locale: String, key: String, vararg vars: Pair<String, Any?>): String {
        val dict = if (locale == "fa") fa else en
        var text = dict[key] ?: en[key] ?: key
        for ((k, v) in vars) {
            text = text.replace("{$k}", v?.toString().orEmpty())
        }
        return text
    }

